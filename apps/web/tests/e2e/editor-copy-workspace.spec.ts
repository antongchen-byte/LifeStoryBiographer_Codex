import {test,expect} from '@playwright/test';
test('owner opens isolated project and all modules retain scope and copied screenplay UID',async({page})=>{
 const scoped:string[]=[];
 const copy={id:'copy-project',title:'Story — Editor copy',actor_id:'owner',config_id:'copy-config',screenplay_id:'copy-screenplay'};
 const project={id:copy.id,title:copy.title,subject_name:'Owner',description:'Copied description',role:'OWNER',status:'intake',media_count:0};
 const screenplay={id:'copy-screenplay',title:'Copied screenplay',project_id:copy.id,interview_uid:'copy-interview',revision:0,cinema_ready:true,source:{},reviewed_markdown:'Copied conversation',materials:[],sections:[],exports:[],state:'idle'};
 const production={id:'copy-production',screenplay_id:screenplay.id,title:screenplay.title,revision:0,interview_uid:'copy-interview',all_approved:false,units:[],renders:[],materials:[]};
 await page.route('**/api/auth/session',r=>r.fulfill({json:{user:{email:'owner@example.com',name:'Owner'},expires:'2099-01-01T00:00:00Z'}}));
 await page.route('**/api/backend/**',r=>{
  const path=new URL(r.request().url()).pathname.replace('/api/backend','');
  if(!path.startsWith('/production/'))scoped.push(r.request().headers()['x-workspace-project']||'missing');
  let body:any=[];
  if(path==='/production/me')body={production_editor:false,actor_id:'owner'};
  if(path.endsWith('/reviews/version'))body={id:'version',title:'Editor version',content:'Page copy',created_at:'2026-11-09T12:00:00Z',module:'screenplay',version_number:1,editor_name:'Editor',can_create_project:true};
  if(path.endsWith('/open-project'))body=copy;
  if(path==='/projects')body=[project];
  if(path===`/projects/${copy.id}`)body=project;
  if(path==='/interviews/options')body={avatars:{flame:'Guide'},personalities:{},genres:{life_story:'Life story'},provider_ready:false,voice_ready:false};
  if(path==='/interviews/configs')body=[{id:'copy-config',project_id:copy.id,name:'Copied Guide',avatar:'flame',genre:'life_story',created_at:'2026-11-09T12:00:00Z'}];
  if(path.endsWith('/configs/copy-config/markdown'))body={markdown:'Copied guide',configuration:{project:copy.id,avatar:'flame',name:'Copied Guide',genre:'life_story',assets:[],scripts:{},recommended:[]}};
  if(path==='/interviews/screenplays')body=[screenplay];
  if(path==='/interviews/screenplays/copy-screenplay')body=screenplay;
  if(path.startsWith('/cinema/'))body=production;
  return r.fulfill({json:body});
 });
 await page.goto('/projects/original/editor-versions/version');
 await page.getByRole('button',{name:'Open as a separate editable project'}).click();
 await expect(page).toHaveURL(/\/projects\/copy-project$/);
 await expect(page.getByText('Isolated editable project:',{exact:false})).toBeVisible();
 await expect(page.getByLabel('Description',{exact:true})).toHaveValue('Copied description');
 const nav=page.getByRole('navigation',{name:'Main navigation'});
 await nav.getByRole('link',{name:/Style Lab/}).click();
 await expect(page.getByLabel('Interviewer name')).toHaveValue('Copied Guide');
 await nav.getByRole('link',{name:/Interview Studio/}).click();
 await expect(page.getByText('Selected interviewer',{exact:true}).locator('..')).toContainText('Copied Guide');
 await nav.getByRole('link',{name:/Screenplay Editor/}).click();
 await expect(page.getByLabel('Conversation Markdown')).toHaveValue('Copied conversation');
 await nav.getByRole('link',{name:/Cinema Studio/}).click();
 await expect(page.getByLabel('Choose your screenplay')).toHaveValue('copy-screenplay');
 await expect(page.getByLabel('Choose your screenplay').locator('option:checked')).toContainText('Screenplay UID: copy-screenplay');
 expect(scoped.length).toBeGreaterThan(5);
 expect(scoped.every(id=>id===copy.id)).toBe(true);
});
